/**
 * A random UUID v4. Unlike `crypto.randomUUID`, works outside a secure context
 * (a self-hosted GUI on plain http).
 *
 * @returns {string}
 */
export const uuidv4 = () => {
    return ([1e7] + -1e3 + -4e3 + -8e3 + -1e11).replace(/[018]/g, c =>
        (c ^ crypto.getRandomValues(new Uint8Array(1))[0] & 15 >> c / 4).toString(16));
};
